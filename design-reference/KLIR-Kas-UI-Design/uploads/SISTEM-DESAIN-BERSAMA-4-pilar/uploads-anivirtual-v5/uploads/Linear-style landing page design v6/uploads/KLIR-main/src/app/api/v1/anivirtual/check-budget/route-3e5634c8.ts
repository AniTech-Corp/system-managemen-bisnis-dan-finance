import { NextRequest, NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import { getUserFromRequest } from '@/lib/auth';

export async function POST(req: NextRequest) {
  try {
    const userPayload = getUserFromRequest(req);
    if (!userPayload) {
      return NextResponse.json({ message: 'Unauthorized' }, { status: 401 });
    }

    const { requestedAmount, category } = await req.json();

    const corPlanProject = await prisma.corPlanProject.findFirst({
      where: { workspaceId: userPayload.workspaceId },
      orderBy: { createdAt: 'desc' },
    });

    const isApproved = requestedAmount <= 50000000;
    const poNumber = isApproved ? `PO-ANIVIRTUAL-${Date.now()}` : null;

    return NextResponse.json({
      status: isApproved ? 'APPROVED_WITHIN_BUDGET' : 'EXCEEDS_CORPLAN_BUDGET',
      requestedAmount,
      category,
      corplanProjectRef: corPlanProject?.title || 'Kedai Kopi Anitech Specialist',
      autoGeneratedPO: poNumber,
    });
  } catch (err: any) {
    return NextResponse.json({ message: err.message }, { status: 500 });
  }
}
